# Two Parameters
def student_info(name, department):
    print("Name:", name)
    print("Department:", department)
    print(name)
    print(department)
student_info("Atul", "CIS")

def add(a, b):
    print(a + b)

add(10, 20)


# Three Parameters
def student(name, age, department):
    print("Name:", name)
    print("Age:", age)
    print("Department:", department)

student("Atul Paul", 21, "CIS")